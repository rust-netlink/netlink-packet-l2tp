fn emit_nla(kind: u16, value: &[u8]) -> Vec<u8> {
    let len = 4 + value.len();
    let aligned_len = (len + 3) & !3;
    let mut raw = vec![0u8; aligned_len];
    emit_u16(&mut raw[0..2], len as u16).unwrap();
    emit_u16(&mut raw[2..4], kind).unwrap();
    raw[4..(4 + value.len())].copy_from_slice(value);
    raw
}
